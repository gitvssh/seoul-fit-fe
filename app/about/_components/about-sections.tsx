export function Section({
  id,
  title,
  lead,
  children,
}: {
  id: string;
  title: string;
  lead?: string;
  children: ReactNode;
}) {
  return (
    <section id={id} aria-labelledby={`${id}-heading`} className='border-t border-border pt-10'>
      <h2 id={`${id}-heading`} className='text-title text-foreground'>
        {title}
      </h2>
      {lead && <p className='mt-2 max-w-prose text-body text-muted-foreground'>{lead}</p>}
      <div className='mt-6'>{children}</div>
    </section>
  );
}

function ExternalLink({ href, children }: { href: string; children: ReactNode }) {
  return (
    <a
      href={href}
      target='_blank'
      rel='noreferrer'
      className='inline-flex items-center gap-1 text-primary underline underline-offset-4'
    >
      {children}
      <ArrowUpRight aria-hidden='true' className='size-3.5' />
    </a>
  );
}

